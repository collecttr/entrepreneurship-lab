function company(
  title: string,
  examples: string[],
  prompt: string,
  compare: string,
): CompanyResearchPrompt {
  return {
    title_ru: title,
    company_examples_ru: examples,
    evidence_required_ru: [
      '≥1 интервью как источник утверждений (не биография для чтения)',
      '≥1 независимый источник (новость, отчёт, filing, реклама, отзыв покупателя)',
      'Фиксация: факт / цифра / цитата / ссылка',
      'Сравнение ≥2 компаний или стратегий по вопросу недели',
    ],
    prompt_ru: prompt,
    compare_focus_ru: compare,
  }
}

function campaign(hint: string, alt: string): CampaignAnalysisPrompt {
  return {
    title_ru: 'Разбор рекламной / коммерческой кампании (доказательства, не «история бренда»)',
    campaign_hint_ru: hint,
    fields_ru: [
      'Ситуация',
      'Аудитория',
      'Цель',
      'Оффер',
      'Сообщение',
      'Каналы',
      'Психология приёмов',
      'CTA',
      'Метрики (если публичны)',
      'Ограничения выводов',
    ],
    alternative_task_ru: alt,
  }
}

