export interface InterviewDef {
  id: string
  title_ru: string
  title_original: string
  url: string
  person: string
  role_ru: string
  company: string
  role_category: InterviewRoleCategory
  /** Minutes when publicly known; null if not confirmed */
  duration_minutes: number | null
  topics: string[]
  skills: string[]
  week_links: number[]
  timestamps: { at: string; label_ru: string }[]
  analysis_questions_ru: string[]
  practical_task_ru: string
  /** Why this interview is evidence for commercial questions — not casual biography reading */
  why_read_ru: string
  /** What to extract: claims, evidence, cross-check, limits, practical conclusion */
  extract_ru: string
  channel: string
  language: 'en' | 'ru' | 'mixed'
  verified_at: string
  http_ok: boolean
}

type InterviewSeed = Omit<InterviewDef, 'why_read_ru' | 'extract_ru'>

function iq(a: string, b: string): string[] {
  return [a, b]
}

function enrichInterview(seed: InterviewSeed): InterviewDef {
  const topicStr = seed.topics.slice(0, 4).join(', ')
  return {
    ...seed,
    why_read_ru: `Доказательная база по темам: ${topicStr}. Связь с навыками: ${seed.skills.join(', ')}. Смотрите, чтобы ответить на исследовательский вопрос недели — не для ознакомительного чтения биографии или «истории бренда».`,
    extract_ru: `Извлеките: (1) ключевые утверждения спикера, (2) какие доказательства он приводит, (3) что кросс-проверить независимым источником, (4) ограничения рассказа, (5) практический вывод для вашего коммерческого вопроса. ${seed.practical_task_ru} Пересказ биографии / всего интервью — не зачёт.`,
  }
}

