export const INTERVIEWS: InterviewDef[] = INTERVIEW_SEEDS.map(enrichInterview)

export function getInterview(id: string): InterviewDef | undefined {
  return INTERVIEWS.find((i) => i.id === id)
}

export function interviewsForWeek(weekNumber: number): InterviewDef[] {
  return INTERVIEWS.filter((i) => i.week_links.includes(weekNumber))
}

export function assertInterviewInvariants(): string[] {
  const errors: string[] = []
  if (INTERVIEWS.length < 40) errors.push(`interviews=${INTERVIEWS.length} < 40`)
  const cats = new Set(INTERVIEWS.map((i) => i.role_category))
  for (const c of Object.keys(INTERVIEW_ROLE_LABELS_RU) as InterviewRoleCategory[]) {
    if (!cats.has(c)) errors.push(`missing role category ${c}`)
  }
  const ids = new Set<string>()
  for (const i of INTERVIEWS) {
    if (ids.has(i.id)) errors.push(`duplicate interview id ${i.id}`)
    ids.add(i.id)
    if (!i.url.startsWith('https://')) errors.push(`bad url ${i.id}`)
    if (!i.http_ok) errors.push(`not verified ${i.id}`)
    if (!i.person.trim()) errors.push(`empty person ${i.id}`)
    if (!i.analysis_questions_ru.length) errors.push(`no analysis q ${i.id}`)
    if (!i.practical_task_ru.trim()) errors.push(`no practical task ${i.id}`)
    if (!i.why_read_ru.trim()) errors.push(`no why_read ${i.id}`)
    if (!i.extract_ru.trim()) errors.push(`no extract ${i.id}`)
  }
  return errors
}
